interface I18nContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string) => string;
  languages: LanguageMeta[];
  mounted: boolean;
}

const I18nContext = createContext<I18nContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (k) => k,
  languages: LANGUAGES,
  mounted: false,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<LanguageCode>('en');
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
    try {
      const saved = localStorage.getItem('cloudsense_lang') as LanguageCode;
      if (saved && TRANSLATIONS[saved]) {
        setLanguageState(saved);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = saved;
        }
        return;
      }
      // Predict language from browser
      const browserLang = navigator.language.split('-')[0].toLowerCase();
      const match = LANGUAGES.find((l) => l.code === browserLang);
      if (match) {
        setLanguageState(match.code);
        if (typeof document !== 'undefined') {
          document.documentElement.lang = match.code;
        }
      }
    } catch {}
  }, []);

  const setLanguage = (lang: LanguageCode) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('cloudsense_lang', lang);
      if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
      }
      // Broadcast to other components/tabs
      window.dispatchEvent(new CustomEvent('cloudsense_language_change', { detail: lang }));
    } catch {}
  };

  const t = (key: string): string => {
    const dict = TRANSLATIONS[language] || TRANSLATIONS.en;
    if (dict && dict[key]) {
      return dict[key];
    }
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    // Return key as fallback
    return key;
  };

  return (
    <I18nContext.Provider value={{ language, setLanguage, t, languages: LANGUAGES, mounted }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
